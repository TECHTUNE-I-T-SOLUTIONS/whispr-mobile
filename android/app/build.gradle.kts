// FCM is optional at build time. The google-services plugin hard-fails if
// android/app/google-services.json is missing, which would break every build
// (including web/CI) until Firebase is configured. Applying it conditionally
// means dropping the file in is the only step left to switch push on.
val googleServicesJson = file("google-services.json")
if (googleServicesJson.exists()) {
    apply(plugin = "com.google.gms.google-services")
} else {
    logger.lifecycle(
        "google-services.json not found - building without FCM. " +
            "Drop the Firebase Android config at android/app/ to enable remote push."
    )
}

// Release signing is read from android/key.properties when present (local
// machine or Codemagic env vars), otherwise it falls back to debug keys so
// `flutter build apk --release` still works for testing.
val keystorePropertiesFile = rootProject.file("key.properties")
val keystoreProperties = java.util.Properties()
val hasReleaseKeystore = keystorePropertiesFile.exists()
if (hasReleaseKeystore) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

